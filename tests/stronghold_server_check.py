def main(only=None):
    bad = known = alt = n = 0
    for mc, rows in GAME.items():
        if only and mc not in only:
            continue
        for (x, z), fy, eyes, chests in rows:
            pf = se.get_stronghold_portal_full(SEED, x, z, mc)
            mine = "".join("1" if e else "0" for e in se.count_stronghold_frames(SEED, x, z, mc))
            ok = pf is not None and pf["frame_y"] == fy and mine == eyes
            bad += not ok
            n += 1
            if not ok:
                print(f"BAD mc {mc} stronghold {x} {z}: frames Y {fy} eyes {eyes} "
                      f"(mine Y {pf and pf['frame_y']} eyes {mine})")
            cards = sl.chests("stronghold", SEED, mc, x, z) or []
            for cx, cy, cz, gs in chests:
                n += 1
                here = [c for c in cards if (c["pos"][0], c["pos"][2]) == (cx, cz) and c.get("seed") is not None]
                main_ = [c for c in here if " — " not in c["name"]]
                if any(c["seed"] == gs and c["pos"][1] == cy for c in main_):
                    continue
                if any(c["seed"] == gs for c in here):
                    alt += 1
                    print(f"alt  mc {mc} chest {cx} {cy} {cz}: the second card")
                    continue
                if (mc, cx, cz) in KNOWN:
                    known += 1
                    continue
                bad += 1
                print(f"BAD mc {mc} chest {cx} {cy} {cz}")
    print("checked", n, "bad", bad, "alt", alt, "known", known)
    return 1 if bad else 0


