def main():
    bad = 0
    for mc, starts in GAME.items():
        bio, _deep = ms.biome_fns(SEED, mc)
        ok = 0
        for (cx, cz), h in starts.items():
            t = ms.has_start(SEED, mc, cx, cz, bio)
            boxes = [tuple(p.bb) for p in ms.layout(SEED, cx, cz, mc=mc)]
            mine = hashlib.md5(repr(boxes).encode()).hexdigest()[:12]
            if t == 1 and mine == h:
                ok += 1
            else:
                bad += 1
                print(f"BAD mc {mc} start {cx} {cz}: type {t}, layout {'OK' if mine == h else 'differs'}")
        print(f"mc {mc}: {ok}/{len(starts)} starts exact")
    print("bad", bad)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
