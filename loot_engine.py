def fill_chest(table_name: str, loot_seed: int, version: str, size: int = 27, world=None):
    """LootTable.fill on an empty container of `size` slots: returns
    (slots: list[Stack|None], approx: list[str])."""
    if _NATIVE is not None:
        r = _NATIVE(table_name, loot_seed, version, size, world)
        if r is not None:
            return r
    return fill_chest_py(table_name, loot_seed, version, size, world)


def fill_chest_py(table_name: str, loot_seed: int, version: str, size: int = 27, world=None):
    """the Python engine itself"""
    tab = get_table(version, table_name)
    if tab is None:
        return None, [f"no table {table_name} in {version}"]
    if loot_seed == 0:
        return None, ["loot seed 0: the game would use the level's random"]
    rnd = JavaRandom(loot_seed)
    ctx = Ctx(rnd, version, world)
    items = []
    roll_table(tab, ctx, items.append, split=True)
    slots = list(range(size))
    java_shuffle(slots, rnd)
    # shuffleAndSplitItems
    split = []
    rest = []
    for st in items:
        if st.count <= 0:
            continue
        if st.count > 1:
            split.append(st)
        else:
            rest.append(st)
    items = rest
    while size - len(items) - len(split) > 0 and split:
        st = split.pop(mth_next_int(rnd, 0, len(split) - 1))
        k = mth_next_int(rnd, 1, st.count // 2)
        cp = st.copy(k)
        st.count -= k
        if st.count > 1 and rnd.next_boolean():
            split.append(st)
        else:
            items.append(st)
        if cp.count > 1 and rnd.next_boolean():
            split.append(cp)
        else:
            items.append(cp)
    items.extend(split)
    java_shuffle(items, rnd)
    out = [None] * size
    for st in items:
        if not slots:
            ctx.approx.append("over-filled container")
            break
        out[slots.pop()] = st
    return out, sorted(set(ctx.approx))
