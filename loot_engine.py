def loot_version(mc: int, sub: str | None = None) -> str | None:
    if sub and sub in _data()["versions"]:
        return sub
    return _MC_TO_LOOT.get(int(mc))


def get_table(version: str, name: str):
    name = name.replace("minecraft:", "")
    if name.startswith("chests/"):
        name = name[len("chests/"):]
    h = _data()["versions"].get(version, {}).get(name)
    return None if h is None else _data()["blobs"][h]


