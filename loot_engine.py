def max_damage(item: str):
    it = item.replace("minecraft:", "")
    if it in _OTHER:
        return _OTHER[it]
    for i, part in enumerate(("_helmet", "_chestplate", "_leggings", "_boots")):
        if it.endswith(part):
            return _DUR.get(it[:-len(part)], (None,) * 4)[i]
    for part in ("_sword", "_pickaxe", "_axe", "_shovel", "_hoe", "_spear"):
        if it.endswith(part):
            return _TOOL.get(it[:-len(part)])
    return None


_ROMAN = ["", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X"]


def roman(n: int) -> str:
    return _ROMAN[n] if 0 <= n < len(_ROMAN) else str(n)


def lx_name(eid: str) -> str:
    return eid.replace("minecraft:", "").replace("_", " ").capitalize()


class Stack:
    __slots__ = ("item", "count", "info", "approx", "ench", "potion", "name_key", "damage")

    def __init__(self, item, count=1):
        self.item = item.replace("minecraft:", "")
        self.count = count
        self.info = []              # human-readable extras (damage, potion, map…)
        self.approx = False
        self.ench = []              # (06/11) [(enchantment id, level)] — the glint, the tooltip
        self.potion = None          # (06/11) potion id (its colour)
        self.name_key = None        # (06/11) set_name's translation key (explorer maps)
        self.damage = None          # (06/11) (durability left, max) — the bar

    def copy(self, count=None):
        s = Stack(self.item, self.count if count is None else count)
        s.info = list(self.info)
        s.approx = self.approx
        s.ench = list(self.ench)
        s.potion, s.name_key, s.damage = self.potion, self.name_key, self.damage
        return s

    def __repr__(self):
        return f"{self.count}× {self.item}" + (f" ({', '.join(self.info)})" if self.info else "")


# ── the evaluator ──────────────────────────────────────────────────────────
def _k(o, *names):
    for n in names:
        if n in o:
            return o[n]
    return None


def _typ(o, *keys):
    t = _k(o, *keys) if isinstance(o, dict) else None
    return (t or "").replace("minecraft:", "")


class Ctx:
    def __init__(self, rnd, version, world=None):
        self.rnd = rnd
        self.version = version
        self.world = world or {}            # e.g. {"biome": "sulfur_caves"}
        self.approx = []                    # reasons the result may be off
        self.depth = 0


def num_int(p, ctx) -> int:
    if isinstance(p, (int, float)):
        return int(p) if isinstance(p, int) else int(p // 1)
    t = _typ(p, "type")
    if t in ("", "uniform") and "min" in p and "max" in p:
        return mth_next_int(ctx.rnd, int(num_float_floor(p["min"], ctx)), int(num_float_floor(p["max"], ctx)))
    if t == "constant":
        return int(p["value"])
    if t == "binomial":
        n = num_int(p["n"], ctx)
        pr = num_float(p["p"], ctx)
        return sum(1 for _ in range(n) if ctx.rnd.next_float() < pr)
    ctx.approx.append(f"number provider {t}")
    return 0


def num_float_floor(p, ctx):
    """Bounds of an int range: their int value (a constant bound is not random)."""
    if isinstance(p, (int, float)):
        return int(p // 1)
    return num_int(p, ctx)


def num_float(p, ctx) -> float:
    if isinstance(p, (int, float)):
        return float(p)
    t = _typ(p, "type")
    if t in ("", "uniform") and "min" in p and "max" in p:
        return mth_next_float(ctx.rnd, num_float(p["min"], ctx), num_float(p["max"], ctx))
    if t == "constant":
        return float(p["value"])
    if t == "binomial":
        return float(num_int(p, ctx))
    ctx.approx.append(f"number provider {t}")
    return 0.0


def _conditions(o):
    c = o.get("conditions")
    if c is None and isinstance(o.get("condition"), dict):
        c = [o["condition"]]
    return c or []


def test_conditions(o, ctx) -> bool:
    for c in _conditions(o):
        if not test_condition(c, ctx):
            return False
    return True


def test_condition(c, ctx) -> bool:
    t = _typ(c, "condition", "type")
    if t == "random_chance":
        return ctx.rnd.next_float() < float(c.get("chance", 0))
    if t == "inverted":
        return not test_condition(c["term"], ctx)
    if t in ("all_of",):
        return all(test_condition(x, ctx) for x in c.get("terms", []))
    if t in ("any_of", "alternative"):
        return any(test_condition(x, ctx) for x in c.get("terms", []))
    if t == "location_check":
        want = (c.get("predicate") or {}).get("biomes") or (c.get("predicate") or {}).get("biome")
        if isinstance(want, list):
            want = [w.replace("minecraft:", "") for w in want]
        elif isinstance(want, str):
            want = [want.replace("minecraft:", "").lstrip("#")]
        b = ctx.world.get("biome")
        if b is None:
            ctx.approx.append("location_check (biome of the chest unknown)")
            return False
        return want is None or b in want
    ctx.approx.append(f"condition {t}")
    return False


def _functions(o):
    f = o.get("functions")
    if f is not None:
        return [(x, _typ(x, "function")) for x in f]
    m = o.get("modifier")
    if m is None:
        return []
    ms = m if isinstance(m, list) else [m]
    out = []
    for x in ms:
        t = _typ(x, "type", "function")
        if t == "sequence":
            for y in x.get("modifiers", x.get("functions", [])):
                out.append((y, _typ(y, "type", "function")))
        else:
            out.append((x, t))
    return out


def apply_functions(st: Stack, o, ctx):
    for f, t in _functions(o):
        if not test_conditions(f, ctx):
            continue
        st = apply_function(st, f, t, ctx)
    return st


def apply_function(st: Stack, f, t, ctx):
    rnd = ctx.rnd
    if t == "set_count":
        add = bool(f.get("add"))
        st.count = (st.count if add else 0) + num_int(f["count"], ctx)
    elif t == "set_damage":
        v = num_float(f["damage"], ctx)
        md = max_damage(st.item)
        pct = 1.0 - max(0.0, min(1.0, v))
        st.info.append(f"durability {max(0, min(100, round((1 - pct) * 100)))} %"
                       if md is None else f"durability {md - (int(pct * md // 1))}/{md}")
        if md is not None:
            st.damage = (md - int(pct * md // 1), md)
    elif t in ("enchant_randomly", "enchant_with_levels"):
        import loot_enchant as lx
        try:
            ench = (lx.enchant_randomly if t == "enchant_randomly" else lx.enchant_with_levels)(st, f, ctx)
        except Exception as e:                      # noqa: BLE001
            ctx.approx.append(f"{t} ({type(e).__name__})")
            st.approx = True
            ench = []
        if ench:
            st.info.append(", ".join(f"{lx_name(i)} {roman(l)}" for i, l in ench))
            st.ench += [(str(i), int(l)) for i, l in ench]
    elif t == "set_potion":
        st.info.append(str(f.get("id", "")).replace("minecraft:", ""))
        st.potion = str(f.get("id", "")).replace("minecraft:", "")
    elif t == "set_stew_effect":
        effs = f.get("effects", [])
        if effs:
            e = effs[rnd.next_int(len(effs))]
            d = num_int(e.get("duration", 0), ctx)
            eff = str(e.get("type", "")).replace("minecraft:", "")
            st.info.append(f"{eff} {d} s")
    elif t == "exploration_map":
        dest = str(f.get("destination", "")).replace("minecraft:", "").replace("#", "")
        st.info.append(f"map → {dest}")
        st.item = "filled_map"
    elif t == "set_instrument":
        # (13/11) HolderSet.getRandomElement: nextInt(size) over the tag's entries, in
        # the order of its file (regular_goat_horns, identical 1.19 → 26.3)
        tag = str(f.get("options", "")).replace("minecraft:", "").replace("#", "")
        opts = GOAT_HORNS.get(tag)
        if opts:
            st.info.append(f"{opts[rnd.next_int(len(opts))]} goat horn")
        else:
            ctx.approx.append(f"set_instrument ({tag})")
            rnd.next_int(4)
    elif t == "set_ominous_bottle_amplifier":
        st.info.append(f"amplifier {max(0, min(4, num_int(f['amplifier'], ctx)))}")
    elif t in ("set_name", "set_lore", "set_components", "set_custom_data", "set_nbt",
               "set_enchantments", "toggle_tooltips", "set_item", "filtered", "discard",
               "set_book_cover", "set_written_book_pages", "set_writable_book_pages",
               "set_banner_pattern", "set_fireworks", "set_firework_explosion",
               "set_custom_model_data", "set_attributes", "limit_count", "furnace_smelt",
               "copy_name", "copy_components", "copy_custom_data", "explosion_decay"):
        if t == "set_enchantments":
            ench = []
            for k, v in (f.get("enchantments") or {}).items():
                lv = v if isinstance(v, int) else (num_int(v, ctx) if isinstance(v, dict) else 1)
                ench.append(f"{lx_name(k.replace('minecraft:', ''))} {roman(int(lv))}")
                st.ench.append((k.replace("minecraft:", ""), int(lv)))
            st.info.append(", ".join(ench))
            if st.item == "book":                 # (06/11) SetEnchantments: a book becomes enchanted
                st.item = "enchanted_book"
        if t == "set_item":
            st.item = str(f.get("item", st.item)).replace("minecraft:", "")
        if t == "set_name":
            nm = f.get("name")
            if isinstance(nm, dict) and nm.get("translate"):
                st.name_key = nm["translate"]
    else:
        ctx.approx.append(f"function {t}")
    return st


def _entry_children(e):
    return e.get("children", [])


def expand_entry(e, ctx, out):
    """LootPoolEntryContainer.expand: the entries that can be picked."""
    t = _typ(e, "type")
    if t in ("alternatives",):
        if not test_conditions(e, ctx):
            return False
        for ch in _entry_children(e):
            if expand_entry(ch, ctx, out):
                return True
        return False
    if t in ("group",):
        if not test_conditions(e, ctx):
            return False
        for ch in _entry_children(e):
            expand_entry(ch, ctx, out)
        return True
    if t in ("sequence",):
        if not test_conditions(e, ctx):
            return False
        for ch in _entry_children(e):
            if not expand_entry(ch, ctx, out):
                return False
        return True
    if not test_conditions(e, ctx):
        return False
    out.append(e)
    return True


def create_items(e, ctx, emit):
    t = _typ(e, "type")
    if t == "item":
        st = Stack(e["name"])
        st = apply_functions(st, e, ctx)
        emit(st)
    elif t == "empty":
        return
    elif t == "loot_table":
        ref = _k(e, "value", "name")
        if isinstance(ref, str):
            tab = get_table(ctx.version, ref)
            if tab is None:
                ctx.approx.append(f"missing table {ref}")
                return
            # NestedLootTable: the entry's functions decorate each item as it is
            # produced (same RNG, interleaved with the nested rolls)
            roll_table(tab, ctx, lambda st: emit(apply_functions(st, e, ctx)), split=False)
        else:
            ctx.approx.append("inline loot table")
    elif t == "tag":
        ctx.approx.append("tag entry")
    else:
        ctx.approx.append(f"entry {t}")


def roll_pool(p, ctx, emit):
    if not test_conditions(p, ctx):
        return
    n = num_int(p.get("rolls", 1), ctx)
    # bonus_rolls × luck = 0 (no luck in a chest)
    for _ in range(n):
        valid = []
        for e in p.get("entries", []):
            expand_entry(e, ctx, valid)
        valid = [(e, int(e.get("weight", 1))) for e in valid if int(e.get("weight", 1)) > 0]
        tot = sum(w for _e, w in valid)
        if not valid or tot == 0:
            continue

        def out(st, p=p):
            emit(apply_functions(st, p, ctx))
        if len(valid) == 1:
            create_items(valid[0][0], ctx, out)
            continue
        idx = ctx.rnd.next_int(tot)
        for e, w in valid:
            idx -= w
            if idx < 0:
                create_items(e, ctx, out)
                break


def _splitter(emit):
    def f(st: Stack):
        mx = max_stack(st.item)
        if st.count < mx:
            emit(st)
        else:
            c = st.count
            while c > 0:
                k = min(mx, c)
                emit(st.copy(k))
                c -= k
    return f


def roll_table(tab, ctx, emit, split=True):
    ctx.depth += 1
    if ctx.depth > 8:
        ctx.approx.append("loot table recursion")
        ctx.depth -= 1
        return
    out = _splitter(emit) if split else emit

    def top(st):
        out(apply_functions(st, tab, ctx))
    for p in tab.get("pools", []):
        roll_pool(p, ctx, top)
    ctx.depth -= 1


