def max_stack(item: str) -> int:
    it = item.replace("minecraft:", "")
    if it in _STACK16 or it.endswith("_sign") or it.endswith("_banner"):
        return 16
    if it in ("heart_of_the_sea", "nether_star"):
        return 64
    for s in _STACK1_SUFFIX:
        if it.endswith(s) or it.startswith(s):
            return 1
    return 64


