"""
loot_engine.py — chest loot exactly as the game rolls it (25/10).

A chest generated by a structure gets a loot table and a « loot table seed »
(StructurePiece.createChest: random.nextLong() of the structure's decoration
RNG). When it is opened, LootTable.fill(container, params, seed) runs with a
java.util.Random seeded with that seed (RandomSource.create → LegacyRandomSource):
    getRandomItems: the pools in order (rolls, weighted entries, functions,
                    then the stack splitter);
    getAvailableSlots: the 27 empty slots, shuffled (Util.shuffle);
    shuffleAndSplitItems: stacks of more than one item split at random, then
                    the list shuffled;
    each stack goes to the LAST remaining slot of the shuffled list.
Read in the 26.3 jar (LootTable, LootPool, Util.shuffle, Mth.nextInt); the same
algorithm since 1.14.

The tables are the game's own data for each version (loot_tables/chests.json.gz,
built by tools/loot/build_loot_data.py), in both formats (« functions » /
« conditions » up to 26.2, « modifier » / « condition » in 26.3).

Enchantments: loot_enchant.py. Not yet modelled (flagged « approximate »):
conditions that need the world (location_check), the goat horn variant.
"""
from __future__ import annotations

import gzip
import json
import os

_M48 = (1 << 48) - 1
_MULT = 0x5DEECE66D


class JavaRandom:
    """java.util.Random (LegacyRandomSource)."""
    __slots__ = ("s", "used")

    def __init__(self, seed: int):
        self.s = (int(seed) ^ _MULT) & _M48
        self.used = 0

    def next(self, bits: int) -> int:
        self.s = (self.s * _MULT + 0xB) & _M48
        self.used += 1
        r = self.s >> (48 - bits)
        if bits == 32 and r >= 1 << 31:
            r -= 1 << 32
        return r

    def next_int(self, bound: int) -> int:
        if bound <= 0:
            raise ValueError("bound must be positive")
        if bound & -bound == bound:                       # power of two
            return (bound * self.next(31)) >> 31
        while True:
            bits = self.next(31)
            val = bits % bound
            if bits - val + (bound - 1) < (1 << 31):
                return val

    def next_float(self) -> float:
        return self.next(24) / float(1 << 24)

    def next_boolean(self) -> bool:
        return self.next(1) != 0

    def next_long(self) -> int:
        v = (self.next(32) << 32) + self.next(32)
        v &= (1 << 64) - 1
        return v - (1 << 64) if v >= 1 << 63 else v


def mth_next_int(rnd: JavaRandom, lo: int, hi: int) -> int:
    return lo if lo >= hi else rnd.next_int(hi - lo + 1) + lo


def mth_next_float(rnd: JavaRandom, lo: float, hi: float) -> float:
    return lo if lo >= hi else rnd.next_float() * (hi - lo) + lo


def java_shuffle(lst: list, rnd: JavaRandom) -> None:
    for i in range(len(lst), 1, -1):
        j = rnd.next_int(i)
        lst[i - 1], lst[j] = lst[j], lst[i - 1]


